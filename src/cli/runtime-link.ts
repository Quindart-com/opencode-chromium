// A single install point that every surface points at, so "which version am I
// running?" is answered by the checkout that is on disk rather than by
// remembering which installer ran last. Nothing here is version-specific: the
// launchers resolve the runtime root at launch time, so the browser
// registration and every client config are written once and never again.
const RUNTIME_MANIFEST = "runtime.json";

export function manifestPath(dir = runtimeDir()) {
  return path.join(dir, RUNTIME_MANIFEST);
}

export function readRuntimeManifest(dir = runtimeDir()) {
  try {
    return parseRuntimeActivation((JSON.parse(fs.readFileSync(manifestPath(dir), "utf8")) as unknown));
  } catch {
    return null;
  }
}

export function writeRuntimeManifest(root: string, dir = runtimeDir()) {
  const resolved = path.resolve(root), version = packageInfo().version ?? "0.0.0";
  const pkg = record(JSON.parse(fs.readFileSync(path.join(resolved, "package.json"), "utf8")) as unknown);
  const desired = { root: resolved,version,contractVersion: Number.isSafeInteger(pkg.toolContractVersion) ? Number(pkg.toolContractVersion) : 1,installedAt: new Date().toISOString() };
  const manifest = { schemaVersion: 2,root: resolved,version,desired,linkedAt: new Date().toISOString(),generation: 0 };
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(manifestPath(dir), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  return manifest;
}

export function launcherPlan(kind: "host" | "mcp" | "plugin") {
  if (kind === "host") return { selection: "controller" as const, entry: "controller/2/control/browser-broker.js" };
  if (kind === "mcp") return { selection: "controller" as const, entry: "controller/2/control/mcp-supervisor.js" };
  return { selection: "desired" as const, entry: "dist/adapters/opencode/index.js" };
}

export function launcherSource(kind: string) {
  const lines = ["#!/usr/bin/env node", "// Stable controller launcher generated by opencode-chromium.",
    "import fs from \"node:fs\";", "import path from \"node:path\";", "import { fileURLToPath,pathToFileURL } from \"node:url\";", "",
    "const dir = path.dirname(fileURLToPath(import.meta.url));", `const activation = JSON.parse(fs.readFileSync(path.join(dir, ${JSON.stringify(RUNTIME_MANIFEST)}), "utf8"));`,
    "const selected = activation.desired ?? activation;", "const root = selected.root;", "process.env.OPENCODE_BROWSER_RUNTIME_DIR ??= dir;",
    "if (activation.stateIsolation === true && [\"development\", \"production\"].includes(activation.channel)) {", "  const state = path.join(dir, \"state\", activation.channel);",
    "  for (const [variable, folder] of Object.entries({ OPENCODE_BROWSER_MEMORY_DIR: \"memory\", AGENT_BROWSER_SEMANTIC_DIR: \"semantic\", AGENT_BROWSER_VISUAL_DIR: \"visual\", AGENT_BROWSER_PROVIDER_DIR: \"providers\", AGENT_BROWSER_ARTIFACT_DIR: \"artifacts\", AGENT_BROWSER_PROFILE_REGISTRY_DIR: \"profiles\" })) process.env[variable] ??= path.join(state, folder);", "}"];
  if (kind === "host") lines.push(`await (await import(pathToFileURL(path.join(dir, ${JSON.stringify(launcherPlan("host").entry)})).href)).runBrowserBroker(dir);`);
  if (kind === "mcp") lines.push(`await (await import(pathToFileURL(path.join(dir, ${JSON.stringify(launcherPlan("mcp").entry)})).href)).superviseMcp(dir);`);
  if (kind !== "plugin") return lines.join("\n") + "\n";
  const entry = launcherPlan("plugin").entry;
  lines.push("if (fs.existsSync(path.join(root, \"src\"))) {", "  const { spawnSync } = await import(\"node:child_process\");",
    "  const build = spawnSync(process.execPath, [path.join(root, \"scripts\", \"build.js\")], { stdio: [\"ignore\", \"ignore\", \"inherit\"] });",
    "  if (build.status !== 0) throw new Error(\"Development runtime build failed\");", "}", `const entry = path.join(root, ${JSON.stringify(entry)});`,
    "if (!fs.existsSync(entry)) throw new Error(`Missing runtime entry: ${entry}`);");
  if (kind === "plugin") {
    // OpenCode imports this module and reads the plugin exports, so they are
    // re-exported from whichever root is active.
    lines.push(
      "const mod = await import(pathToFileURL(entry).href);",
      "export default mod.default;",
      "export const opencodeBrowserPlugin = mod.opencodeBrowserPlugin;",
      "export const opencodeV2Plugin = mod.opencodeV2Plugin;",
      "export const opencodePluginModule = mod.opencodePluginModule;",
      "export const createOpenCodeSetup = mod.createOpenCodeSetup;",
    );
    return lines.join("\n") + "\n";
  }
  return lines.join("\n") + "\n";
}

function statusSource() {
  return [
    "#!/usr/bin/env node",
    "// Generated by `opencode-chromium link`.",
    "import path from \"node:path\";",
    "import { fileURLToPath, pathToFileURL } from \"node:url\";",
    "",
    "const dir = path.dirname(fileURLToPath(import.meta.url));",
    "const { createController } = await import(pathToFileURL(path.join(dir, \"controller/2/control/controller.js\")).href);",
    "process.stdout.write(`${JSON.stringify(createController({ dir }).status(), null, 2)}\\n`);",
  ].join("\n") + "\n";
}

function writeExecutable(filePath: string, contents: string | NodeJS.ArrayBufferView) {
  fs.writeFileSync(filePath, contents, "utf8");
  if (process.platform !== "win32") fs.chmodSync(filePath, 0o755);
  return filePath;
}

export function writeLaunchers(root: string, dir = runtimeDir()) {
  fs.mkdirSync(dir, { recursive: true });
  for (const file of supervisorFiles(dir)) { fs.mkdirSync(path.dirname(file.filePath), { recursive: true }); fs.writeFileSync(file.filePath, file.after!, "utf8"); }
  const version = packageInfo().version ?? "0.0.0";
  fs.writeFileSync(path.join(dir, "controller.json"), JSON.stringify({ protocolVersion: 2,controllerVersion: version,globalCliVersion: version,installedAt: new Date().toISOString() }, null, 2) + "\n");
  const launchers = {
    host: writeExecutable(path.join(dir, "host.mjs"), launcherSource("host")),
    mcp: writeExecutable(path.join(dir, "mcp.mjs"), launcherSource("mcp")),
    plugin: writeExecutable(path.join(dir, "plugin.mjs"), launcherSource("plugin")),
    status: writeExecutable(path.join(dir, "status.mjs"), statusSource()),
  };
  // The browser registration already points at this filename, so rewriting it
  // is enough: no registry or manifest change is needed on re-link.
  const wrapper = process.platform === "win32" ? path.join(dir, "opencode-browser-host.cmd") : path.join(dir, "opencode-browser-host");
  writeExecutable(wrapper, process.platform === "win32"
    ? `@echo off\r\n"${process.execPath}" "${launchers.host}"\r\n`
    : `#!/usr/bin/env sh\nexec "${process.execPath}" "${launchers.host}"\n`);
  return { ...launchers, wrapper, dir };
}

// Point every agent-facing surface at the launchers. Each config is rewritten
// in place from a backup, so re-linking is idempotent and reversible.
export function linkClientSurfaces({ dir = runtimeDir(), clients = ["codex", "opencode", "dsh"], dryRun = false } = {}) {
  const mcp = path.join(dir, "mcp.mjs");
  const plugin = path.join(dir, "plugin.mjs");
  const results = [];
  for (const client of clients) {
    if (client === "codex") {
      results.push(installClient({ client: "codex", serverPath: mcp, dryRun }));
      continue;
    }
    if (client === "opencode") {
      results.push(installClient({ client: "opencode", pluginPath: plugin, dryRun }));
      continue;
    }
    if (client === "dsh") {
      results.push(patchDshConfig(configPath("dsh"), mcp, dryRun));
      continue;
    }
    results.push({ client, skipped: true, reason: "unsupported surface" });
  }
  return { mcp, plugin, results };
}

// Legacy link shares the validated YAML planner used by setup/update.
export function patchDshConfig(filePath: string, target: string, dryRun = false) {
  if (!fs.existsSync(filePath)) return { client: "dsh", path: filePath, changed: false, reason: "not installed" };
  const result = updateClientConfig({ client: "dsh", filePath, serverPath: target, dryRun });
  return { client: "dsh", path: filePath, changed: result.changed, next: target, backup: result.backup };
}

// Chromium resolves a native messaging host through several registry roots and
// stops at the first valid manifest. A browser that identifies itself as
// Chromium -- Brave in particular -- can therefore look in the shared Chrome
// root rather than its own, so a host registered only under the browser's own
// root can stay invisible and every connectNative fails as
// "Specified native messaging host not found". `chrome` is always a target for
// that reason: it costs one JSON file and one key when Chrome is absent, and it
// is the difference between working and not when it is the root actually read.
const SHARED_CHROMIUM_ROOTS = ["chrome"];

// Browsers to register: the ones present, the shared Chromium root, plus any
// already registered. Keeping an existing registration matters because a
// browser's executable can live somewhere we do not look, and never removing
// one keeps this from breaking a working setup.
export function linkTargets(dir = runtimeDir()) {
  const registered = browserIds().filter((browser) => readRegistration(browser, dir).registered);
  return [...new Set([...installedBrowsers(), ...SHARED_CHROMIUM_ROOTS, ...registered])];
}

export function linkRuntime({ root = packageRoot(), dir = runtimeDir(), dryRun = false, browsers = null }: { root?: string; dir?: string; dryRun?: boolean; browsers?: string[] | null } = {}) {
  const resolvedRoot = path.resolve(root);
  const targets = browsers ?? linkTargets(dir);
  if (dryRun) return { dryRun: true, root: resolvedRoot, dir, browsers: targets, manifest: manifestPath(dir), skills: skillTargets() };
  const launchers = writeLaunchers(resolvedRoot, dir);
  const manifest = writeRuntimeManifest(resolvedRoot, dir);
  const nativeHost = installManifest({
    auto: true,
    browsers: targets,
    extensionIds: [],
    hostPath: process.platform === "win32" ? launchers.wrapper : launchers.host,
  });
  const skills = installSkills({});
  return { root: resolvedRoot, dir, manifest, launchers, nativeHost, skills };
}

export function runtimeStatus({ root = packageRoot() } = {}) {
  const dir = runtimeDir();
  const manifest = readRuntimeManifest(dir);
  const resolvedRoot = path.resolve(root);
  const canonicalSkill = directoryHash(skillSourceDirectory()).sha256;
  const wrapper = path.join(dir, process.platform === "win32" ? "opencode-browser-host.cmd" : "opencode-browser-host");
  const installed = installedBrowsers();
  return {
    hostName: HOST_NAME,
    runtimeDir: dir,
    linked: manifest !== null && samePath(manifest.root, resolvedRoot),
    manifest,
    root: resolvedRoot,
    version: packageInfo().version ?? null,
    branch: git(["rev-parse", "--abbrev-ref", "HEAD"], resolvedRoot),
    revision: git(["rev-parse", "--short", "HEAD"], resolvedRoot),
    dirty: (git(["status", "--porcelain"], resolvedRoot) ?? "") !== "",
    // Whether the browser will actually load us, not merely that a file exists.
    browserHost: { path: wrapper, installed: fs.existsSync(wrapper) },
    installedBrowsers: installed,
    registration: browserIds().map((browser) => ({ ...readRegistration(browser, dir), installed: installed.includes(browser) })),
    build: buildStatus(resolvedRoot),
    skills: skillTargets().map((target) => ({
      path: target,
      parity: fs.existsSync(path.join(target, "SKILL.md")) && directoryHash(target).sha256 === canonicalSkill,
    })),
    hosts: runningHosts(resolvedRoot),
  };
}

function git(args: readonly string[], cwd: string) {
  try {
    return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

// Best effort: when the OS will not let us enumerate processes we report null
// and the extension's own reconnect still picks up the new code. A host is
// short-lived by design -- the extension starts one on demand -- so finding
// none is normal rather than a fault.
function processRows(value: unknown) { return (Array.isArray(value) ? value : [value]).map(record); }
function runningHosts(root = packageRoot()) {
  const needles = [
    path.join(root, "native-host", "src", "host.js"),
    path.join(runtimeDir(), "host.mjs"),
  ].map((candidate) => candidate.replaceAll("\\", "/").toLowerCase());
  try {
    const rows = process.platform === "win32"
      ? processRows((JSON.parse(execFileSync("powershell", ["-NoProfile", "-Command", "Get-CimInstance Win32_Process -Filter \"Name='node.exe'\" | Select-Object ProcessId,CommandLine | ConvertTo-Json -Compress"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], windowsHide: true }) || "[]") as unknown))
      : execFileSync("ps", ["-eo", "pid=,args="], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })
        .split("\n").map((line) => line.trim().match(/^(\d+)\s+(.*)$/)).filter((match): match is RegExpMatchArray => match !== null)
        .map((match) => ({ ProcessId: Number(match[1]), CommandLine: match[2] }));
    return rows
      .filter((row) => {
        const commandLine = String(row.CommandLine ?? "").replaceAll("\\", "/").toLowerCase();
        return needles.some((needle) => commandLine.includes(needle));
      })
      .map((row) => ({ pid: row.ProcessId }));
  } catch {
    return null;
  }
}

export function syncRuntime({ root = packageRoot(), quiet = false, ifLinked = false } = {}) {
  const resolvedRoot = path.resolve(root);
  // Git hooks call this with --if-linked so it stays inert on a checkout that
  // was never linked to a runtime, which keeps the hook harmless for everyone
  // else working in the repository.
  if (ifLinked) {
    const manifest = readRuntimeManifest();
    if (!manifest || !samePath(manifest.root, resolvedRoot)) return { root: resolvedRoot, skipped: "not linked" };
  }
  const before = buildStatus(resolvedRoot);
  let rebuilt = false;
  if (before.stale) {
    execFileSync(process.execPath, [path.join(resolvedRoot, "scripts", "build.js")], { stdio: quiet ? "ignore" : "inherit" });
    rebuilt = true;
  }
  const hosts = runningHosts(resolvedRoot);
  return { root: resolvedRoot, rebuilt, fresh: !buildStatus(resolvedRoot).stale, stoppedHosts: [], hostsSupported: hosts !== null,
    pendingReload: Boolean(hosts?.length), instruction: "Reconnect tools after active work finishes; sync never interrupts running hosts" };
}

